ERROS_DE_PASSO = (OSError, RuntimeError, ValueError, TimeoutError)


def rodar_passos(seco, aviso=None):
    """Roda os passos; um que falha nao impede os outros. aviso(i, total, ia, titulo, estado, mudou) a cada passo
    (estado: "rodando", "ok" ou "erro: <tipo>: <mensagem>"). Devolve (tudo o que mudou, houve falha)."""
    import subprocess
    mudou_tudo, falhou = [], False
    total = len(PASSOS)
    for i, (ia, titulo, funcao) in enumerate(PASSOS, 1):
        if aviso:
            aviso(i, total, ia, titulo, "rodando", [])
        mudou = []
        try:
            funcao(seco, mudou)
            estado = "ok"
        except (*ERROS_DE_PASSO, subprocess.SubprocessError) as e:
            falhou = True
            estado = f"erro: {type(e).__name__}: {str(e)[:300]}"
            print(f"{titulo}: {type(e).__name__}: {e}", file=sys.stderr)
        mudou_tudo += mudou
        if aviso:
            aviso(i, total, ia, titulo, estado, mudou)
    return mudou_tudo, falhou


def _aviso_json(i, total, ia, titulo, estado, mudou):
    print(json.dumps({"passo": i, "total": total, "ia": ia, "titulo": titulo, "title": TITULOS_EN.get(titulo, titulo),
                      "estado": estado,
                      "mudou": mudou[:50]}, ensure_ascii=False), flush=True)


