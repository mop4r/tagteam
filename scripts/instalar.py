def _eh_juncao(caminho):
    try:
        return os.path.isjunction(caminho)
    except AttributeError:          # Python sem isjunction
        return os.path.realpath(caminho) != os.path.abspath(caminho)


def montar_mcp():
    atual = ler_json(os.path.join(CONFIG, "mcp_config.json"), {})
    atual = atual if isinstance(atual, dict) else {}
    servidores = atual.setdefault("mcpServers", {})
    for nome, cfg in (ler_json(os.path.join(HOME, ".claude.json"), {}).get("mcpServers") or {}).items():
        if not isinstance(cfg, dict) or cfg.get("type") == "sse":
            continue
        novo = {k: cfg[k] for k in MCP_CHAVES if k in cfg}
        if "command" in novo or "url" in novo:
            servidores[nome] = novo           # o do Claude manda: definicao mudada la (token novo) muda aqui
    return atual


def montar_hooks():
    atual = ler_json(os.path.join(CONFIG, "hooks.json"), {})
    atual = atual if isinstance(atual, dict) else {}
    # o comando roda por "cmd /c" na pasta do hooks.json. Caminho relativo sem espaco evita o problema de
    # aspas do cmd /c; o ".\" e obrigatorio: com NoDefaultCurrentDirectoryInExePath=1 (o Claude Code liga)
    # o cmd nao procura programa na pasta atual
    atual[NOME_HOOK] = {"Stop": [{"type": "command", "command": ".\\gancho-antigravity.cmd", "timeout": 15}]}
    return atual


def tirar_hook_antigravity(seco, mudou):
    """Antigravity desmarcado para conversas: tira o hook claude-sync (os hooks dos outros ficam) e o .cmd dele."""
    caminho = os.path.join(CONFIG, "hooks.json")
    atual = ler_json(caminho, None)
    if isinstance(atual, dict) and NOME_HOOK in atual:
        atual.pop(NOME_HOOK)
        gravar(caminho, atual, seco, mudou)
    apagar(os.path.join(CONFIG, "gancho-antigravity.cmd"), seco, mudou)


def apagar(caminho, seco, mudou):
    if os.path.isfile(caminho):
        mudou.append(f"apagado {caminho}")
        if not seco:
            os.remove(caminho)


def apagar_se_gerado(caminho, seco, mudou):
    """Apaga um arquivo que o TagTeam gerou inteiro (comeca com MARCA_GERADO); o que outra pessoa escreveu fica."""
    try:
        with open(caminho, encoding="utf-8") as f:
            primeira = f.readline().strip()
    except OSError:
        return
    if primeira == MARCA_GERADO:
        apagar(caminho, seco, mudou)


